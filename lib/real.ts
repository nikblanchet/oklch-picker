/**
 * Colors which both a screen can show and a dye or paint can produce.
 *
 * The picker works with chroma relative to this limit, so that every position
 * of every control is a valid color.
 */
import { clamp, type Lch, round } from './color.ts'
import { isLinearInGamut, oklchToLinear } from './gamut.ts'

export interface Pick {
  readonly h: number
  readonly l: number
  /** From gray (0) to the boldest real color (1). */
  readonly s: number
}

/** No fabric is as black or as white as a screen. */
