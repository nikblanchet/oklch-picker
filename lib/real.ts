function surfaceLimit(l: number, h: number): number {
  const y = clamp(0, (l - DARKEST) / ROW_STEP, SURFACES.length - 1.001)
  const x = h / COLUMN_STEP
  const [top, left] = [Math.floor(y), Math.floor(x)]
  const [a, b] = [SURFACES[top]!, SURFACES[top + 1]!].map(row => {
    const from = row[left % row.length]!
    return from + (row[(left + 1) % row.length]! - from) * (x - left)
  }) as [number, number]
  return (a + (b - a) * (y - top)) / 1000
}

export function maxChroma(l: number, h: number): number {
  let max = surfaceLimit(l, h)
  if (isLinearInGamut(oklchToLinear(l, max, h))) return max
  let min = 0
  while (max - min > 0.00005) {
    const c = (min + max) / 2
    if (isLinearInGamut(oklchToLinear(l, c, h))) {
      min = c
    } else {
      max = c
    }
  }
  return min
}

export function toLch({ h, l, s }: Pick): Lch {
  return { c: round(s * maxChroma(l, h), 5), h: round(h, 3), l: round(l, 5) }
}

export function isReal({ c, h, l }: Lch): boolean {
  return l >= DARKEST && l <= LIGHTEST && c <= maxChroma(l, h) + 0.001
}

/** The closest real color of the same hue. */
export function toPick(color: Lch): Pick {
  const { c, h } = color
  const miss = (l: number) =>
    Math.hypot(l - color.l, Math.max(0, c - maxChroma(l, h)))
  let best = clamp(DARKEST, color.l, LIGHTEST)
  if (!isReal(color)) {
    for (let l = DARKEST; l <= LIGHTEST; l += 0.005) {
      if (miss(l) < miss(best)) best = l
    }
  }
  return { h, l: best, s: Math.min(1, c / maxChroma(best, h)) }
}

/** The same kind of color for everybody, to study how it primes guesses. */
export function randomPick(): Pick {
  const h = Math.floor(360 * Math.random())
  return { h, l: 0.7, s: Math.min(1, 0.1 / maxChroma(0.7, h)) }
}
